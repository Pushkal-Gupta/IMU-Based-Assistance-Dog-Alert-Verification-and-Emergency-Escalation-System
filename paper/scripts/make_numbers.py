    N["grid.t1long.median"] = f(g[(120.0, 120.0)]["median_time_to_human_s"], 0)
    N["grid.t1long.preach"] = pct(g[(120.0, 120.0)]["burden_at_measured_far"]["p_reaches_caregiver"])
    N["grid.ship.median"] = f(g[(60.0, 120.0)]["median_time_to_human_s"], 0)
    tor = {row["parameter"]: row["values"] for row in sim["tornado_owner_asleep"]}
    for horizon in ("180", "300"):
        vals = [v[f"p_human_within_{horizon}"] for row in tor.values() for v in row]
        N[f"tornado.p{horizon}.min"] = pct(min(vals))
        N[f"tornado.p{horizon}.max"] = pct(max(vals))
    for param, key in (("caregiver.p_responds", "care"), ("caregiver.median_s", "caremed"),
                       ("owner_asleep.p_responds", "owner")):
        row = tor[param]
        N[f"tornado.{key}.lo"] = pct(row[0]["p_human_within_180"])
        N[f"tornado.{key}.hi"] = pct(row[-1]["p_human_within_180"])
        N[f"tornado.{key}.vlo"] = f(row[0]["value"], 2 if row[0]["value"] < 1 else 0)
        N[f"tornado.{key}.vhi"] = f(row[-1]["value"], 2 if row[-1]["value"] < 1 else 0)

    write_results_tables(research, results, abl)

    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "numbers.tex").write_text(N.tex())
    (OUT / "numbers.json").write_text(json.dumps(N.values, indent=1, sort_keys=True) + "\n")
    print(f"wrote {len(N.values)} numbers to {OUT / 'numbers.tex'}")
    return 0


