# formatting
# --------------------------------------------------------------------------- #
def f(x, d=3):
    if x is None or (isinstance(x, float) and not math.isfinite(x)):
        return "n/a"
    return f"{x:.{d}f}"


def pct(x, d=1):
    return "n/a" if x is None else f"{100 * x:.{d}f}"


def i(x):
    s = f"{int(round(x)):,}"
    return s.replace(",", "{,}")


def signed(x, d=3):
    """A number with a typographic minus, safe in text mode."""
    s = f(x, d)
    return f"$-${s[1:]}" if s.startswith("-") else s


def ci(d, k=3, scale=1.0):
    """An interval as [low, high]; negative bounds get a proper minus."""
    return f"[{signed(d['low'] * scale, k)}, {signed(d['high'] * scale, k)}]"


def sci(x, d=1):
    m, e = f"{x:.{d}e}".split("e")
    return f"${m}\\times10^{{{int(e)}}}$"


class Numbers:
    def __init__(self) -> None:
        self.values: dict[str, str] = {}

    def __setitem__(self, key: str, value) -> None:
        if key in self.values:
            raise KeyError(f"duplicate key {key}")
        self.values[key] = str(value)

    def tex(self) -> str:
        lines = [
            "% GENERATED by paper/scripts/make_numbers.py -- do not edit.",
            "\\makeatletter",
            "\\DeclareRobustCommand{\\R}[1]{\\ifcsname rnum@#1\\endcsname\\csname rnum@#1\\endcsname"
            "\\else\\textbf{\\textcolor{red}{??#1??}}\\PackageWarning{numbers}{undefined number #1}\\fi}",
        ]
        for k, v in sorted(self.values.items()):
            lines.append(f"\\expandafter\\def\\csname rnum@{k}\\endcsname{{{v}}}")
        lines.append("\\makeatother")
        return "\n".join(lines) + "\n"


