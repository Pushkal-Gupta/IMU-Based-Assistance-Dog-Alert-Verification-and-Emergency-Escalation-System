def write_results_tables(research, results, abl) -> None:
    TABLES.mkdir(parents=True, exist_ok=True)
    order = ["heuristic_baseline", "naive_bayes", "logistic_regression", "svm", "random_forest",
             "random_forest_embedded"]
    lines = []
    for m in order:
        iv = research["logo_intervals"][m]
        cell = lambda k: f"{f(iv[k]['estimate'])} {{\\scriptsize {ci(iv[k])}}}"
        w = results["within_subject"][m]["f1"]
        lines.append(f"{PRETTY[m]} & {f(w)} & {cell('segment_f1')} & {cell('segment_roc_auc')} & "
                     f"{cell('event_recall')} & {cell('event_specificity')}\\\\")
    for name, label in (("hist_gradient_boosting", "Gradient boosting (features)"),
                        ("rocket_2000", "ROCKET, 2000 kernels (raw)"), ("cnn_1d", "1-D CNN (raw)")):
        r = abl["baselines"][name]
        lines.append(f"{label} & --- & {f(r['segment_f1'])} & {f(r['segment_auc'])} {{\\scriptsize {ci(r['segment_auc_ci'])}}} & "
                     f"{f(r['event_recall'])} & {f(r['event_specificity'])}\\\\")
    lines.insert(len(order), "\\midrule")
    (TABLES / "logo.tex").write_text("\n".join(lines) + "\n")

    lines = []
    for m in ("heuristic_baseline", "random_forest", "random_forest_embedded"):
        row = [PRETTY[m]]
        for proto in ("leave_one_session_out", "leave_one_device_out"):
            r = research["shift"][proto][m]
            row += [f(r["segment"]["f1"]), f(r["segment"]["roc_auc"]), f(r["event"]["recall"]), f(r["event"]["specificity"])]
        lines.append(" & ".join(row) + "\\\\")
